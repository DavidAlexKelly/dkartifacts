/**
 * Generates `src/core/fallbacks.ts` from @acc/decho-styling's `tokens.json`.
 *
 *     npm run fallbacks
 *
 * WHY THIS EXISTS
 * ---------------
 * The components style themselves with `var(--decho-color-surface, #111318)`.
 * The variable is what makes them follow a theme; the fallback is what makes
 * them correct with no theme, no stylesheet and no dependency on the styling
 * package. Both halves are needed, and the fallback half is a copy of somebody
 * else's values — which is the drift this estate has already paid for twice.
 *
 * So it is generated, and `src/core/fallbacks.test.ts` fails if the checked-in
 * file and the styling package disagree. Same arrangement as that package's
 * own `gen-tokens-css.mjs`: edit nothing here by hand, run the script, commit
 * both, and let the test catch you when you forget.
 *
 * WHY THE FALLBACKS ARE THE *CLASSIC* THEME AND NOT SOME NEUTRAL DEFAULT
 * ----------------------------------------------------------------------
 * Because `skinVariables(skin)` emits only a theme's *deltas from the base
 * set*. Given base-set fallbacks, a token some theme overrides resolves to
 * that theme's value and a token it leaves alone resolves to the base — which
 * is exactly `tokensFor(skin)`, token for token. The two mechanisms agree
 * without either knowing the other exists. Any other fallback choice breaks
 * that identity and the parity test says so.
 *
 * WHY IT READS THE SIBLING SOURCE RATHER THAN A DEPENDENCY
 * -------------------------------------------------------
 * A devDependency on @acc/decho-styling would make `npm install` in this repo
 * depend on a published version of a package that is developed in the same
 * commit. Reading the file out of the monorepo keeps generation honest and
 * install boring. If these packages are ever split into separate repos, point
 * TOKENS_JSON at `require.resolve("@acc/decho-styling/tokens.json")` and add
 * the devDependency then.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const TOKENS_JSON = resolve(here, "../../decho-styling/src/tokens.json");
const OUT = resolve(here, "../src/core/fallbacks.ts");

/**
 * `color.surfaceRaised` → `--decho-color-surface-raised`.
 *
 * Deliberately a re-implementation of the styling package's
 * `tokenVariableName` rather than an import of it: importing would need that
 * package built, and the parity test compares the two anyway, so a divergence
 * is caught rather than assumed away.
 */
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const variableName = (group, key) => `--decho-${kebab(group)}-${kebab(key)}`;

const json = JSON.parse(readFileSync(TOKENS_JSON, "utf8"));
const classic = json.themes?.classic;
if (classic == null) {
  throw new Error(
    `No \`themes.classic\` in ${TOKENS_JSON}. Regenerate it with ` +
      `\`npm run tokens\` in packages/decho-styling first.`,
  );
}

/** `"#111318"` → `"var(--decho-color-surface, #111318)"`. */
function declaration(group, key, value) {
  return `var(${variableName(group, key)}, ${value})`;
}

function renderGroup(group, entries, transform) {
  const lines = [`  ${JSON.stringify(group)}: {`];
  for (const [key, value] of Object.entries(entries)) {
    lines.push(`    ${JSON.stringify(key)}: ${JSON.stringify(transform(group, key, value))},`);
  }
  lines.push("  },");
  return lines.join("\n");
}

const groups = Object.entries(classic);

const body = `/**
 * GENERATED by scripts/gen-fallbacks.mjs from @acc/decho-styling's tokens.json.
 * Do not edit. Run \`npm run fallbacks\` and commit the result;
 * \`fallbacks.test.ts\` fails if this file and that package disagree.
 *
 * Two views of the same ${groups.length} token groups:
 *
 *   BASE_TOKENS  the literal values of the \`classic\` theme.
 *   VAR_TOKENS   each one as \`var(--decho-…, <literal>)\`.
 *
 * VAR_TOKENS is what every recipe reads, which is the whole theming mechanism:
 * inside a themed element the variable wins, outside one the literal does, and
 * neither case needs a stylesheet or an import.
 */

/** The \`classic\` values, as literals. Useful for canvas, charts and tests. */
export const BASE_TOKENS = {
${groups.map(([g, entries]) => renderGroup(g, entries, (_g, _k, v) => v)).join("\n")}
} as const;

/** The same tokens as \`var()\` references with the \`classic\` value as fallback. */
export const VAR_TOKENS = {
${groups.map(([g, entries]) => renderGroup(g, entries, declaration)).join("\n")}
} as const;
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);

const count = groups.reduce((n, [, entries]) => n + Object.keys(entries).length, 0);
console.log(`fallbacks.ts: ${count} tokens in ${groups.length} groups, from classic`);
