/**
 * `decho css` — generate a theme's CSS so nobody hand-copies hex values.
 *
 * WHY THIS EXISTS
 * ---------------
 * Two estates adopted the accent option by pasting the output of
 * `accentVariables()` into a stylesheet, and separately calling
 * `withAccent()` in a TypeScript theme module. Two halves of one decision,
 * kept in step by hand — which is precisely the drift this package was built
 * to remove, reintroduced at the consumer.
 *
 * With this, the stylesheet is generated from the same function the TypeScript
 * calls, and regenerating is a build step rather than an act of discipline:
 *
 *     npx decho css --theme modern --accent "#2fbf71" --out src/styles/decho-theme.css
 *
 * Put that line in a `pretest`/`prebuild` script and the CSS cannot go stale.
 *
 * WHAT IT EMITS, AND WHY ONLY THAT
 * --------------------------------
 * Only the variables that differ from the theme being extended. A block of
 * thirty identical declarations buries the two that matter, in the file and in
 * devtools — and a consumer diffing an upgrade wants to see what moved, not
 * what was restated.
 */

import { writeFileSync } from "node:fs";

export async function css(args, pkg) {
  const theme = args.theme ?? "classic";
  const accent = args.accent;
  const selector = args.selector ?? ":root";

  const themes = ["classic", ...Object.keys(pkg.SKIN_OVERRIDES)];
  if (!themes.includes(theme)) {
    console.error(`decho css: unknown theme "${theme}". Known: ${themes.join(", ")}`);
    process.exitCode = 1;
    return;
  }

  const variables = {
    // The theme's own overrides, so a consumer can ship one file rather than
    // importing tokens.css and then overriding it.
    ...(args.full === true ? pkg.tokenVariables(theme) : pkg.skinVariables(theme)),
    ...(accent != null ? pkg.accentVariables(theme, accent) : {}),
  };

  if (accent != null && Object.keys(pkg.accentVariables(theme, accent)).length === 0) {
    // withAccent returns the theme untouched for an unparseable colour, so an
    // empty diff means the colour was rejected — silence here would ship a
    // stylesheet that quietly does nothing.
    console.error(`decho css: "${accent}" is not a colour I can parse.`);
    process.exitCode = 1;
    return;
  }

  const declarations = Object.entries(variables)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");

  const command = [
    "npx decho css",
    `--theme ${theme}`,
    accent != null ? `--accent "${accent}"` : "",
    args.full === true ? "--full" : "",
    `--selector "${selector}"`,
  ]
    .filter(Boolean)
    .join(" ");

  const out = `/* ${"=".repeat(72)}
   GENERATED by @acc/decho-styling — do not edit.

     ${command}

   Theme: ${theme}${accent != null ? `, re-tinted to ${accent}` : ""}
   Package version: ${pkg.version ?? "unknown"}

   Regenerate after changing the colour or upgrading the package. Putting the
   command in a prebuild script is the point: a hand-maintained copy of these
   values is the drift this package exists to remove.

   ${
     accent != null
       ? `Only what the accent owns is listed. Shadows keep their near-black
   stops — a shadow is darkness, not brand — and any second hue a theme mixes
   in (modern's teal hairline stop) survives.`
       : `Only what this theme changes from the defaults is listed.`
   }
   ${"=".repeat(72)} */

${selector} {
${declarations}
}
`;

  if (args.out != null) {
    writeFileSync(args.out, out);
    console.log(
      `decho css: wrote ${Object.keys(variables).length} variables to ${args.out}`,
    );
  } else {
    process.stdout.write(out);
  }
}
